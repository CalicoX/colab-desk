export function resolveLanguage(pref, systemLang = "") {
  if (pref === "en") return "en";
  if (pref === "zh-CN" || pref === "zh") return "zh-CN";
  return /^zh/i.test(String(systemLang || "")) ? "zh-CN" : "en";
}

