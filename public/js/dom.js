const domCache = new Map();

// Lazily resolves and caches connected DOM elements so lazily-mounted modals work transparently.
export const dom = {};
for (const [key, selector] of Object.entries(DOM_SELECTORS)) {
  Object.defineProperty(dom, key, {
    enumerable: true,
    get() {
      const cached = domCache.get(key);
      if (cached && cached.isConnected) return cached;
      const el = document.querySelector(selector);
      if (el) domCache.set(key, el);
      return el;
    },
  });
}

export function openDialog(dlg) {
  if (!dlg) return;
  if (typeof dlg.showModal === "function") {
    if (!dlg.open) dlg.showModal();
  } else {
    dlg.setAttribute("open", "");
  }
}

export function closeDialog(dlg) {
  if (!dlg) return;
  if (typeof dlg.close === "function") {
    if (dlg.open) dlg.close();
  } else {
    dlg.removeAttribute("open");
  }
}
